# Top-level keys the kit computes itself; extra_json may add new keys and
# deep-merge into ``source``, but must not overwrite these (doing so could
# clobber the proof block or forge the skill name).
_RESERVED_TOP_KEYS = frozenset(
    {
        "skill",
        "currency",
        "year",
        "rate",
        "rate_direction",
        "foreign_per_usd",
        "usd_per_foreign",
        "proof",
        "caveats",
    }
)


def _validate_extra_json(extra: object) -> None:
    if not isinstance(extra, dict):
        raise RateError("extra_json must be a dict.", 2)
    clobbered = _RESERVED_TOP_KEYS & set(extra)
    if clobbered:
        raise RateError(
            f"extra_json must not overwrite reserved keys: {', '.join(sorted(clobbered))}.", 2
        )
    if "source" in extra and not isinstance(extra["source"], dict):
        raise RateError("extra_json['source'] must be a dict to merge into the source block.", 2)


def _deep_merge(base: dict, extra: dict) -> dict:
    """Overlay ``extra`` onto ``base`` in place, recursing into nested dicts.

    Year-end's ``source.year_end_confirmed`` is nested, so a shallow update
    would clobber the whole ``source`` block. Dict-vs-dict collisions recurse;
    every other collision takes the ``extra`` value.
    """
    for key, value in extra.items():
        if isinstance(value, dict) and isinstance(base.get(key), dict):
            _deep_merge(base[key], value)
        else:
            base[key] = value
    return base


def _copy_saved_proofs(folder: Path, saved_proofs: Iterable[Path], *, proof_required: bool) -> list[dict[str, object]]:
    """Copy each proof into the packet folder and record its hashed entry.

    ``proof_required`` determines whether an unusable proof raises ``RateError``
    or is skipped.
    """
    entries: list[dict[str, object]] = []
    for index, original_path in enumerate(saved_proofs, start=1):
        proof_path = original_path
        # is_file() (not exists()) so a directory or broken symlink fails as a
        # clean RateError instead of an IsADirectoryError from copy2/hashing.
        if not proof_path.is_file():
            if proof_required:
                raise RateError(f"Proof file does not exist or is not a regular file: {proof_path}", 2)
            continue
        if proof_path.parent.resolve() != folder.resolve():
            copied_name = f"source-proof-{index}{proof_path.suffix}"
            copied_path = folder / copied_name
            shutil.copy2(proof_path, copied_path)
            proof_path = copied_path
        entries.append(
            {
                "filename": proof_path.name,
                "packet_relative_path": proof_path.name,
                "path": as_abs(proof_path),
                "sha256": sha256_file(proof_path),
            }
        )
    return entries


def build_workpaper(spec: WorkpaperSpec) -> dict[str, object]:
    """Build the proof packet (md + json + pdf + copied/hashed proofs).

    Writes into ``<output_root>/<code>-<year>-<slug(source_title)>/`` and
    returns the workpaper dict (carrying a stripped ``_presentation`` block for
    the cited-answer helpers). Always warns to stderr when replacing an
    existing packet - the hardened behavior both skills now inherit.
    """
    foreign_per_usd, usd_per_foreign = build_rate_values(spec.rate, spec.rate_direction)
    if spec.extra_json:
        _validate_extra_json(spec.extra_json)
    try:
        year = int(spec.year)
    except (TypeError, ValueError) as exc:
        raise RateError(f"Year must be an integer, got {spec.year!r}.", 2) from exc
    source_slug = slugify(spec.source_title)
    # Slug the currency code and use an int year so neither can inject a path
    # separator or traversal sequence into the packet folder.
    folder = Path(spec.output_root) / f"{slugify(spec.currency_code)}-{year}-{source_slug}"
    if (folder / "workpaper.json").exists():
        print(f"note: replacing existing workpaper packet at {folder}", file=sys.stderr)
    folder.mkdir(parents=True, exist_ok=True)

    proof_entries = _copy_saved_proofs(folder, spec.saved_proofs, proof_required=spec.proof_required)
    proof_limitations = list(spec.proof_limitations)
    if spec.proof_required and not proof_entries:
        proof_limitations = proof_limitations + [NO_PROOF_LIMITATION]

    workpaper: dict[str, object] = {
        "skill": spec.skill_name,
        "currency": spec.currency_code,
        "year": year,
        "rate": fmt_decimal(spec.rate),
        "rate_direction": spec.rate_direction,
        "foreign_per_usd": fmt_decimal(foreign_per_usd),
        "usd_per_foreign": fmt_decimal(usd_per_foreign),
        "source": {
            "title": spec.source_title,
            "url": spec.source_url,
            "category": spec.source_category,
            "retrieved": spec.retrieval_date,
            "note": spec.source_note,
        },
        "proof": {
            "workpaper_md": as_abs(folder / "workpaper.md"),
            "workpaper_json": as_abs(folder / "workpaper.json"),
            "workpaper_pdf": as_abs(folder / "workpaper.pdf"),
            "saved_files": proof_entries,
            "limitations": proof_limitations,
        },
        "caveats": list(spec.caveats),
    }

    if spec.extra_json:
        _deep_merge(workpaper, spec.extra_json)

    workpaper[_PRESENTATION_KEY] = {
        "document_title": spec.document_title,
        "document_subtitle": spec.document_subtitle,
        "rate_phrase": spec.rate_phrase,
        "extra_rows": list(spec.extra_rows),
    }

    markdown_text = render_workpaper_md(workpaper)
    (folder / "workpaper.md").parent.mkdir(parents=True, exist_ok=True)
    (folder / "workpaper.md").write_text(markdown_text, encoding="utf-8")

    pdf_path = folder / "workpaper.pdf"
    pdf_path.write_bytes(render_workpaper_pdf_bytes(workpaper))
    proof_block = workpaper["proof"]
    assert isinstance(proof_block, dict)
    proof_block["workpaper_pdf_sha256"] = sha256_file(pdf_path)

    serializable = {key: value for key, value in workpaper.items() if not key.startswith("_")}
    (folder / "workpaper.json").write_text(
        json.dumps(serializable, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    return workpaper
